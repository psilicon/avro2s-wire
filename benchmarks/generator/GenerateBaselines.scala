package avrogen.benchmarks.generator

import avro2s.generator.{CodeGenerator, CodeWriter, EnumType, GeneratorConfig}
import avro2s.language.ScalaVersion
import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.databind.node.ObjectNode
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Path}
import java.security.MessageDigest
import org.apache.avro.Schema
import org.apache.avro.compiler.specific.SpecificCompiler

/** Run inside the pinned avro2s Scala 3 build; see scripts/regenerate-baselines.sh. */
object GenerateBaselines:
  def main(args: Array[String]): Unit =
    require(args.isEmpty, "Paths are supplied through AVROGEN_BASELINE_ROOT")
    val root = Path.of(sys.env("AVROGEN_BASELINE_ROOT")).toAbsolutePath.normalize
    val commit = sys.env("AVROGEN_BASELINE_COMMIT")
    require(commit == "8342d5bd467aca16265b1f083b8b6b667929ee37", "Unexpected avro2s revision")
    val avroVersion = classOf[Schema].getPackage.getImplementationVersion
    require(avroVersion == "1.12.1", s"Expected Apache Avro 1.12.1, found $avroVersion")
    val sourceSchema = root.resolve("fixtures/src/main/resources/avro/Trade.avsc")
    val json = Files.readString(sourceSchema, UTF_8)
    val mapper = new ObjectMapper()

    def schema(namespace: String): Schema =
      val tree = mapper.readTree(json).asInstanceOf[ObjectNode]
      tree.put("namespace", namespace)
      new Schema.Parser().setValidateDefaults(true).parse(mapper.writeValueAsString(tree))

    def save(relativePath: String, text: String): Path =
      val path = root.resolve(relativePath)
      Files.createDirectories(path.getParent)
      Files.writeString(path, text, UTF_8)

    val scalaSchema = schema("avrogen.benchmarks.avro2s")
    val javaSchema = schema("avrogen.benchmarks.javaavro")
    val scalaInput = save("benchmarks/generator/avro2s/Trade.avsc", scalaSchema.toString(true) + "\n")
    val javaInput = save("benchmarks/generator/javaavro/Trade.avsc", javaSchema.toString(true) + "\n")
    val config = GeneratorConfig(
      targetScalaVersion = ScalaVersion.Scala_3,
      logicalTypesEnabled = false,
      enumType = EnumType.JavaEnum
    )
    val generated = CodeGenerator.generateCode(List(scalaSchema), config)
    require(generated.map(_.path) == List("avrogen/benchmarks/avro2s/Trade.scala"), "Unexpected generated Scala files")
    CodeWriter.writeToDirectory(root.resolve("benchmarks/src/main/scala").toString)(generated)

    val compiler = new SpecificCompiler(javaSchema)
    compiler.setOutputCharacterEncoding("UTF-8")
    // A null source always regenerates output rather than checking input timestamps.
    compiler.compileToDestination(null, root.resolve("benchmarks/src/main/java").toFile)

    val scalaOutput = root.resolve("benchmarks/src/main/scala/avrogen/benchmarks/avro2s/Trade.scala")
    val javaOutput = root.resolve("benchmarks/src/main/java/avrogen/benchmarks/javaavro/Trade.java")
    def sha256(path: Path): String =
      MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(path)).map(byte => f"${byte & 0xff}%02x").mkString

    val manifest = Vector(
      "# Generated by scripts/regenerate-baselines.sh; no timestamp so regeneration is deterministic.",
      s"avro2s.commit=$commit",
      "avro2s.projectVersion=0.29.0-SNAPSHOT",
      "avro2s.scalaVersion=3.3.6",
      "avro2s.targetScalaVersion=Scala_3",
      "avro2s.logicalTypesEnabled=false",
      "avro2s.enumType=JavaEnum",
      s"apacheAvro.version=$avroVersion",
      "apacheAvro.stringType=CharSequence (default)",
      "apacheAvro.outputCharacterEncoding=UTF-8",
      "apacheAvro.otherOptions=SpecificCompiler defaults",
      s"fixture.schema.sha256=${sha256(sourceSchema)}",
      s"avro2s.schema.sha256=${sha256(scalaInput)}",
      s"javaAvro.schema.sha256=${sha256(javaInput)}",
      s"avro2s.source.sha256=${sha256(scalaOutput)}",
      s"javaAvro.source.sha256=${sha256(javaOutput)}"
    ).mkString("\n") + "\n"
    save("benchmarks/generator/baselines.properties", manifest)
    println(s"Generated genuine avro2s and Apache Avro baselines in ${root.resolve("benchmarks")}")
