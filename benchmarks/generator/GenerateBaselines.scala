package avro2s.wire.benchmarks.generator

import avro2s.generator.{CodeGenerator, CodeWriter, EnumType, GeneratorConfig}
import avro2s.language.ScalaVersion
import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.databind.node.ObjectNode
import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Path}
import java.security.MessageDigest
import org.apache.avro.Schema
import org.apache.avro.compiler.specific.SpecificCompiler
import scala.jdk.CollectionConverters.*

/** Run inside the pinned avro2s Scala 3 build; see scripts/regenerate-baselines.sh. */
object GenerateBaselines:
  def main(args: Array[String]): Unit =
    require(args.isEmpty, "Paths are supplied through AVRO2S_WIRE_BASELINE_ROOT")
    val root = Path.of(sys.env("AVRO2S_WIRE_BASELINE_ROOT")).toAbsolutePath.normalize
    val commit = sys.env("AVRO2S_WIRE_BASELINE_COMMIT")
    require(commit == "8342d5bd467aca16265b1f083b8b6b667929ee37", "Unexpected avro2s revision")
    val avroVersion = classOf[Schema].getPackage.getImplementationVersion
    require(avroVersion == "1.12.1", s"Expected Apache Avro 1.12.1, found $avroVersion")
    val sourceSchema = root.resolve("fixtures/src/main/resources/avro/Trade.avsc")
    val json = Files.readString(sourceSchema, UTF_8)
    val mapper = new ObjectMapper()

    def schema(namespace: String): Schema =
      val tree = mapper.readTree(json).asInstanceOf[ObjectNode]
      tree.put("namespace", namespace)
      new Schema.Parser().setValidateDefaults(true).parse(mapper.writeValueAsString(tree))

    def save(relativePath: String, text: String): Path =
      val path = root.resolve(relativePath)
      Files.createDirectories(path.getParent)
      Files.writeString(path, text, UTF_8)

    val scalaSchema = schema("avro2s.wire.benchmarks.avro2s")
    val javaSchema = schema("avro2s.wire.benchmarks.javaavro")
    val scalaInput = save("benchmarks/generator/avro2s/Trade.avsc", scalaSchema.toString(true) + "\n")
    val javaInput = save("benchmarks/generator/javaavro/Trade.avsc", javaSchema.toString(true) + "\n")
    val config = GeneratorConfig(
      targetScalaVersion = ScalaVersion.Scala_3,
      logicalTypesEnabled = false,
      enumType = EnumType.JavaEnum
    )
    val generated = CodeGenerator.generateCode(List(scalaSchema), config)
    require(generated.map(_.path) == List("avro2s/wire/benchmarks/avro2s/Trade.scala"), "Unexpected generated Scala files")
    CodeWriter.writeToDirectory(root.resolve("benchmarks/src/main/scala").toString)(generated)

    val compiler = new SpecificCompiler(javaSchema)
    compiler.setOutputCharacterEncoding("UTF-8")
    // A null source always regenerates output rather than checking input timestamps.
    compiler.compileToDestination(null, root.resolve("benchmarks/src/main/java").toFile)

    val scalaOutput = root.resolve("benchmarks/src/main/scala/avro2s/wire/benchmarks/avro2s/Trade.scala")
    val javaOutput = root.resolve("benchmarks/src/main/java/avro2s/wire/benchmarks/javaavro/Trade.java")
    def sha256(path: Path): String =
      MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(path)).map(byte => f"${byte & 0xff}%02x").mkString

    val manifest = Vector(
      "# Generated by scripts/regenerate-baselines.sh; no timestamp so regeneration is deterministic.",
      s"avro2s.commit=$commit",
      "avro2s.projectVersion=0.29.0-SNAPSHOT",
      "avro2s.scalaVersion=3.3.6",
      "avro2s.targetScalaVersion=Scala_3",
      "avro2s.logicalTypesEnabled=false",
      "avro2s.enumType=JavaEnum",
      s"apacheAvro.version=$avroVersion",
      "apacheAvro.stringType=CharSequence (default)",
      "apacheAvro.outputCharacterEncoding=UTF-8",
      "apacheAvro.otherOptions=SpecificCompiler defaults",
      s"fixture.schema.sha256=${sha256(sourceSchema)}",
      s"avro2s.schema.sha256=${sha256(scalaInput)}",
      s"javaAvro.schema.sha256=${sha256(javaInput)}",
      s"avro2s.source.sha256=${sha256(scalaOutput)}",
      s"javaAvro.source.sha256=${sha256(javaOutput)}"
    ).mkString("\n") + "\n"
    save("benchmarks/generator/baselines.properties", manifest)
    val comparisonInputs = Files.list(root.resolve("fixtures/src/main/resources/avro/comparison"))
    val comparisonSchemas = try comparisonInputs.iterator().asScala.filter(_.toString.endsWith(".avsc")).toVector.sortBy(_.toString)
      finally comparisonInputs.close()
    val comparisonManifest = Vector.newBuilder[String]
    comparisonManifest ++= Vector(
      "# Generated by scripts/regenerate-baselines.sh; no timestamp.",
      s"avro2s.commit=$commit", "avro2s.logicalTypesEnabled=true", "avro2s.enumType=JavaEnum",
      s"apacheAvro.version=$avroVersion", "apacheAvro.stringType=CharSequence (default)",
      "apacheAvro.enableDecimalLogicalType=true", "avro2s.excluded=ComparisonDecimal (decimal logical conversions unsupported)"
    )
    val customRoots = Vector.newBuilder[String]
    comparisonSchemas.foreach { input =>
      val tree = mapper.readTree(Files.readString(input, UTF_8)).asInstanceOf[ObjectNode]
      val name = tree.get("name").asText()
      def relocated(namespace: String): Schema =
        val copy = tree.deepCopy()
        copy.put("namespace", namespace)
        new Schema.Parser().setValidateDefaults(true).parse(mapper.writeValueAsString(copy))
      def remember(path: Path): Unit =
        comparisonManifest += s"sha256.${root.relativize(path).toString}=${sha256(path)}"
      remember(input)
      if name != "ComparisonDecimal" then
        val s = relocated("avro2s.wire.benchmarks.comparison.avro2s")
        remember(save(s"benchmarks/generator/comparison/avro2s/$name.avsc", s.toString(true) + "\n"))
        val sources = CodeGenerator.generateCode(List(s), config.copy(logicalTypesEnabled = true))
        sources.foreach { source =>
          val language = if source.path.endsWith(".java") then "java" else "scala"
          CodeWriter.writeToDirectory(root.resolve(s"benchmarks/src/main/$language").toString)(List(source))
          remember(root.resolve(s"benchmarks/src/main/$language/${source.path}"))
        }
      val j = relocated("avro2s.wire.benchmarks.comparison.javaavro")
      remember(save(s"benchmarks/generator/comparison/javaavro/$name.avsc", j.toString(true) + "\n"))
      val specific = new SpecificCompiler(j)
      specific.setOutputCharacterEncoding("UTF-8")
      specific.setEnableDecimalLogicalType(true)
      specific.compileToDestination(null, root.resolve("benchmarks/src/main/java").toFile)
      val generatedRoot = root.resolve(s"benchmarks/src/main/java/avro2s/wire/benchmarks/comparison/javaavro/$name.java")
      val custom = "hasCustomCoders\\(\\)\\s*\\{\\s*return true;".r.findFirstIn(Files.readString(generatedRoot, UTF_8)).nonEmpty
      comparisonManifest += s"java.customCoders.$name=$custom"
      if custom then customRoots += name
    }
    val javaSources = Files.list(root.resolve("benchmarks/src/main/java/avro2s/wire/benchmarks/comparison/javaavro"))
    try javaSources.iterator().asScala.filter(_.toString.endsWith(".java")).toVector.sortBy(_.toString).foreach { path =>
      comparisonManifest += s"sha256.${root.relativize(path).toString}=${sha256(path)}"
    } finally javaSources.close()
    val customNames = customRoots.result()
    val probeSource = """// Generated test/setup probes; genuine baseline records remain unmodified.
package avro2s.wire.benchmarks.comparison

import org.apache.avro.io.{Encoder, ResolvingDecoder}
import org.apache.avro.specific.SpecificRecordBase

trait DispatchCounts:
  var encodeCalls = 0
  var decodeCalls = 0

object ComparisonCustomProbes:
  def create(name: String): SpecificRecordBase & DispatchCounts = name match
""" + customNames.map(name => s"    case \"$name\" => new Counting$name\n").mkString +
      "    case other => throw new IllegalArgumentException(s\"No generated custom coder for $other\")\n\n" +
      customNames.map { name => s"""private final class Counting$name extends javaavro.$name with DispatchCounts:
  override def customEncode(out: Encoder): Unit =
    encodeCalls += 1
    super.customEncode(out)
  override def customDecode(in: ResolvingDecoder): Unit =
    decodeCalls += 1
    super.customDecode(in)

""" }.mkString
    val probe = save("benchmarks/src/main/scala/avro2s/wire/benchmarks/comparison/ComparisonCustomProbes.scala", probeSource)
    comparisonManifest += s"sha256.${root.relativize(probe).toString}=${sha256(probe)}"
    save("benchmarks/generator/comparison-baselines.properties", comparisonManifest.result().mkString("\n") + "\n")
    println(s"Generated genuine avro2s and Apache Avro baselines in ${root.resolve("benchmarks")}")
